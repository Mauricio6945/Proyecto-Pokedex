const LanguageContext = createContext(null);

// Proveedor que conserva el idioma, lo aplica al documento y expone funciones de traducción.
export function I18nProvider({ children }) {
  const [language, setLanguage] = useState(() => {
    // Recupera el idioma guardado por el usuario o usa español como valor inicial.
    const saved = window.localStorage.getItem("pokedex-language");
    return saved === "en" ? "en" : "es";
  });

  // Guarda la preferencia y sincroniza el atributo lang de la página al cambiar de idioma.
  useEffect(() => {
    window.localStorage.setItem("pokedex-language", language);
    document.documentElement.lang = language;
  }, [language]);

  // Memoriza las funciones públicas para evitar recrearlas en cada renderizado.
  const value = useMemo(() => ({
    language,
    setLanguage,
    t: (key, variables = {}) => Object.entries(variables).reduce(
      (result, [name, replacement]) => result.replaceAll(`{${name}}`, () => String(replacement)),
      translations[language][key] ?? translations.es[key] ?? key,
    ),
    translateError: (message) => {
      const errorKeys = {
        "Debes iniciar sesión": "errorAuth",
        "Origen de solicitud no autorizado": "errorOrigin",
        "Carta no válida": "errorInvalidCard",
        "Carta no encontrada": "errorCardMissing",
        "Mazo no encontrado": "errorDeckMissing",
        "El nombre debe tener entre 1 y 60 caracteres": "errorDeckName",
        "Ya tienes un mazo con ese nombre": "errorDuplicateDeck",
        "La carta no está en tu inventario": "errorCardNotOwned",
        "Este mazo ya contiene todas las copias que tienes de esta carta": "errorDeckCopies",
        "Carta no encontrada en el mazo": "errorDeckCardMissing",
        "Error interno del servidor": "errorServer",
        "Endpoint no encontrado": "errorEndpoint",
      };
      const key = errorKeys[message];
      return key ? translations[language][key] : message;
    },
  }), [language]);

  // Hace disponible el contexto de traducción para todos los componentes descendientes.
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

// Hook seguro que entrega el contexto de idioma y evita su uso fuera del proveedor.
export function useI18n() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useI18n debe usarse dentro de I18nProvider");
  return context;
}
